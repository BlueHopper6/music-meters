const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const { compositionProject, imageLayer, normalizeProject } = require('../../phase2/project.cjs')
const { assetData, saveArtwork, resolveArtwork } = require('../../phase2/assets.cjs')

test('artwork is copied beside JSON, unsafe references are rejected, and missing files fail clearly', () => {
  const root = path.resolve(__dirname, '..', '..', 'artifacts', 'phase4')
  fs.mkdirSync(root, { recursive: true })
  const dir = fs.mkdtempSync(path.join(root, 'asset-test-'))
  const image = path.join(dir, 'source.png')
  fs.writeFileSync(image, Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVQIHWP4z8DwHwAFgAI/ScL/nwAAAABJRU5ErkJggg==', 'base64'))
  const target = path.join(dir, 'review.json')
  const project = compositionProject()
  project.layers.push({ ...imageLayer(), imagePath: image })
  const stored = saveArtwork(normalizeProject(project), target)
  assert.match(stored.layers.at(-1).imagePath, /^review\.assets\/[a-f0-9]{64}\.png$/)
  const opened = resolveArtwork(stored, target)
  assert.ok(fs.existsSync(opened.layers.at(-1).imagePath))
  assert.match(assetData(opened)[opened.layers.at(-1).imagePath], /^data:image\/png;base64,/)
  assert.throws(() => resolveArtwork({ ...stored, layers: [{ ...stored.layers.at(-1), imagePath: '../private.png' }] }, target), /Invalid project artwork reference/)
  fs.unlinkSync(opened.layers.at(-1).imagePath)
  assert.throws(() => assetData(opened), /ENOENT/)
})
