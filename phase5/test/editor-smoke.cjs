const fs = require('node:fs')
const path = require('node:path')
const assert = require('node:assert/strict')
const { createHash } = require('node:crypto')
const { app } = require('electron')
const { readPreferences } = require('../../phase2/preferences.cjs')
const { BUILTINS } = require('../../phase2/templates.cjs')

const dir = process.env.PHASE5_GATE_DIR
const delay = ms => new Promise(resolve => setTimeout(resolve, ms))
module.exports = async function phase5Smoke(win) {
  const evaluate = expression => win.webContents.executeJavaScript(expression)
  const click = id => evaluate(`document.getElementById(${JSON.stringify(id)}).click()`)
  async function waitFor(expression, label, timeout = 180000) {
    const deadline = Date.now() + timeout
    while (Date.now() < deadline) {
      if (await evaluate(expression)) return
      await delay(100)
    }
    throw new Error(`Timed out for ${label}; status: ${await evaluate('document.querySelector("#status").textContent')}`)
  }
  const set = (id, value, type = 'change') => evaluate(`(() => { const el=document.getElementById(${JSON.stringify(id)});
    el.value=${JSON.stringify(value)}; el.dispatchEvent(new Event(${JSON.stringify(type)},{bubbles:true})); return true })()`)
  async function still(name) {
    const encoded = await evaluate('document.getElementById("stage").toDataURL("image/png").split(",")[1]')
    fs.writeFileSync(path.join(dir, name), Buffer.from(encoded, 'base64'))
  }
  async function time(seconds) {
    await set('time-input', String(seconds))
    await waitFor(`document.querySelector('#status').textContent.includes('Real Prism') &&
      document.querySelector('#time-input').value === '${Number(seconds).toFixed(2)}' && document.querySelector('#preview-busy').hidden`, `${seconds}s preview`)
  }
  await waitFor('document.querySelector("#status").textContent.includes("Real Prism")', 'song A preview')
  assert.equal(await evaluate('document.querySelector("#export-preset").value'), '1080p')
  assert.equal(await evaluate('document.querySelectorAll("#template-list option").length'), BUILTINS.length)
  await set('template-list', 'starter:Observatory')
  await click('load-template')
  await waitFor('document.querySelectorAll(".layer-item").length === 18 && document.querySelector("#status").textContent.includes("Real Prism")', 'starter layout')
  await evaluate('document.querySelector("[data-id=observatory-spectrum]").click()')
  await set('layer-x', '85')
  await evaluate('document.querySelector("[data-id=observatory-artwork]").click()')
  await click('image-choose')
  await waitFor('document.querySelector("#image-name").textContent.includes("art-A")', 'art A')
  assert.equal(await evaluate('document.querySelector("#layer-visible").checked'), true)
  await time(2)
  await still('song-A-preview.png')
  await set('template-name', 'My Studio Layout')
  await click('save-template')
  await waitFor('document.querySelector("#status").textContent.includes("Saved layout template")', 'template save')
  const templateId = await evaluate('document.querySelector("#template-list").value')
  assert.match(templateId, /^[a-f0-9-]{36}$/)
  await click('save-template')
  await waitFor('!document.querySelector("#template-conflict-modal").hidden', 'template conflict modal (choose different name)')
  await click('template-conflict-rename')
  await waitFor('document.querySelector("#template-conflict-modal").hidden && document.querySelector("#status").textContent.includes("Choose a different template name")', 'template conflict rename')
  assert.equal(await evaluate('document.activeElement.id'), 'template-name')
  assert.equal(await evaluate('document.querySelectorAll("#template-list option").length'), BUILTINS.length + 1)
  await click('save-template')
  await waitFor('!document.querySelector("#template-conflict-modal").hidden', 'template conflict modal (replace)')
  await click('template-conflict-replace')
  await waitFor('document.querySelector("#template-conflict-modal").hidden && document.querySelector("#status").textContent.includes("Replaced layout template: My Studio Layout")', 'template conflict replace')
  assert.equal(await evaluate('document.activeElement.id'), 'template-name')
  assert.equal(await evaluate('document.querySelector("#template-list").value'), templateId)
  assert.equal(await evaluate('document.querySelectorAll("#template-list option").length'), BUILTINS.length + 1)
  const templateFile = path.join(process.env.PHASE5_TEST_USER_DATA, 'templates', `${templateId}.json`)
  const storedTemplate = JSON.parse(fs.readFileSync(templateFile, 'utf8'))
  assert.equal(storedTemplate.layout.audioPath, '')
  assert.equal(storedTemplate.layout.layers.find(layer => layer.id === 'observatory-artwork').imagePath, '')
  assert.equal(storedTemplate.layout.layers.find(layer => layer.id === 'observatory-spectrum').x, 85)
  await set('template-name', 'My Studio Copy')
  await click('duplicate-template')
  await waitFor('document.querySelector("#status").textContent.includes("Duplicated layout template")', 'template duplicate')
  const copyId = await evaluate('document.querySelector("#template-list").value')
  assert.notEqual(copyId, templateId)
  await set('template-name', 'Renamed Studio Copy')
  await click('rename-template')
  await waitFor('document.querySelector("#status").textContent.includes("Renamed layout template")', 'template rename')
  assert.equal(await evaluate('document.querySelector("#template-list").selectedOptions[0].textContent'), 'Renamed Studio Copy')
  await click('open-template-manager')
  await waitFor('!document.querySelector("#template-manager-modal").hidden', 'open template manager')
  assert.equal(await evaluate('document.activeElement.id'), 'template-manager-close')
  assert.equal(await evaluate(`(() => { const last = Array.from(document.querySelectorAll('#template-manager-modal button')).at(-1);
    last.focus(); last.dispatchEvent(new KeyboardEvent('keydown', { key: 'Tab', bubbles: true, cancelable: true }));
    return document.activeElement.id })()`), 'template-manager-close')
  assert.equal(await evaluate(`(() => { const first = document.getElementById('template-manager-close');
    first.dispatchEvent(new KeyboardEvent('keydown', { key: 'Tab', shiftKey: true, bubbles: true, cancelable: true }));
    return document.activeElement.dataset.action })()`), 'delete')
  assert.equal(await evaluate('document.querySelectorAll("#template-manager-builtins .template-manager-row").length'), BUILTINS.length)
  assert.equal(await evaluate('document.querySelectorAll("#template-manager-builtins [data-action=rename], #template-manager-builtins [data-action=delete]").length'), 0)
  assert.equal(await evaluate('document.querySelectorAll("#template-manager-custom .template-manager-row").length'), 2)
  await evaluate('document.querySelector("#template-manager-builtins .template-manager-row [data-action=duplicate]").click()')
  await waitFor('document.querySelector("#template-manager-custom .template-manager-rename-input") !== null', 'duplicate factory template in manager')
  await evaluate(`(() => { const input = document.querySelector("#template-manager-custom .template-manager-rename-input"); input.value = "Managed Spectrum"; return true })()`)
  await evaluate('document.querySelector("#template-manager-custom [data-action=save-rename]").click()')
  await waitFor('document.querySelector("#template-manager-status").textContent.includes("Renamed layout template: Managed Spectrum")', 'rename custom template in manager')
  assert.equal(await evaluate('document.activeElement.dataset.action'), 'rename')
  assert.equal(await evaluate('document.querySelectorAll("#template-manager-custom .template-manager-row").length'), 3)
  await evaluate('Array.from(document.querySelectorAll("#template-manager-custom .template-manager-row")).find(row => row.textContent.includes("Managed Spectrum")).querySelector("[data-action=delete]").click()')
  await waitFor('document.querySelector("#template-manager-custom [data-action=confirm-delete]") !== null', 'confirm delete prompt in manager')
  await evaluate('document.querySelector("#template-manager-custom [data-action=confirm-delete]").click()')
  await waitFor('document.querySelector("#template-manager-status").textContent.includes("Deleted layout template: Managed Spectrum")', 'delete custom template in manager')
  assert.equal(await evaluate('document.activeElement.id'), 'template-manager-close')
  assert.equal(readPreferences(process.env.PHASE5_TEST_USER_DATA).lastTemplateId, '')
  assert.equal(await evaluate('document.querySelectorAll("#template-manager-custom .template-manager-row").length'), 2)
  await click('template-manager-close')
  await waitFor('document.querySelector("#template-manager-modal").hidden', 'close template manager')
  await set('template-list', templateId)
  await click('import-audio')
  await waitFor('document.querySelector("#audio-name").textContent.includes("song-B-880") && document.querySelector("#status").textContent.includes("Real Prism")', 'song B import')
  await click('load-template')
  await waitFor('document.querySelector("#status").textContent.includes("Real Prism") && document.querySelector("#preview-busy").hidden', 'song B layout')
  assert.equal(await evaluate('document.querySelector("#title").value'), 'song B 880')
  assert.equal(await evaluate('document.querySelector("[data-id=observatory-spectrum]") !== null'), true)
  process.env.PHASE4_TEST_IMAGE_PATH = process.env.PHASE5_TEST_ART_B
  await evaluate('document.querySelector("[data-id=observatory-artwork]").click()')
  await click('image-choose')
  await waitFor('document.querySelector("#image-name").textContent.includes("art-B")', 'art B')
  await evaluate('document.querySelector("[data-id=observatory-song-name]").click()')
  await set('text-content', 'SONG B FINAL')
  await time(2)
  await still('song-B-preview.png')
  const digest = name => createHash('sha256').update(fs.readFileSync(path.join(dir, name))).digest('hex')
  assert.notEqual(digest('song-A-preview.png'), digest('song-B-preview.png'))
  await click('save-project')
  await waitFor('document.querySelector("#status").textContent.includes("Saved project")', 'song B save')
  const storedProject = JSON.parse(fs.readFileSync(process.env.PHASE2_TEST_PROJECT_PATH, 'utf8'))
  assert.match(storedProject.audioRelativePath, /song-B-880\.wav$/)
  assert.equal(storedProject.layers.find(layer => layer.id === 'observatory-spectrum').x, 85)
  assert.equal(storedProject.layers.find(layer => layer.id === 'observatory-song-name').text, 'SONG B FINAL')
  await click('open-project')
  await waitFor('document.querySelector("#status").textContent.includes("Real Prism") && document.querySelector("#preview-busy").hidden', 'song B reopen')
  assert.equal(await evaluate('document.querySelector("#audio-name").textContent.includes("song-B-880")'), true)
  assert.equal(await evaluate('document.querySelector("#missing-media").hidden'), true)
  await click('render-mp4')
  await waitFor('document.querySelector("#status").textContent.includes("MP4 ready:")', 'song B 1080p export', 240000)
  assert.ok(fs.existsSync(process.env.PHASE2_TEST_OUTPUT_PATH))
  const outputHash = createHash('sha256').update(fs.readFileSync(process.env.PHASE2_TEST_OUTPUT_PATH)).digest('hex')
  await delay(1000)
  await click('render-mp4')
  await waitFor('document.querySelector("#status").textContent.includes("Output already exists")', 'existing output error')
  assert.equal(createHash('sha256').update(fs.readFileSync(process.env.PHASE2_TEST_OUTPUT_PATH)).digest('hex'), outputHash)
  const preferences = JSON.parse(fs.readFileSync(path.join(process.env.PHASE5_TEST_USER_DATA, 'workflow-preferences.json'), 'utf8'))
  assert.equal(preferences.lastTemplateId, templateId)
  assert.equal(preferences.exportPreset, '1080p')
  await set('title', 'Keep My Project Name', 'input')
  process.env.PHASE2_TEST_IMPORT_PATH = path.join(dir, 'song-A-440.wav')
  await click('import-audio')
  await waitFor('document.querySelector("#audio-name").textContent.includes("song-A-440") && document.querySelector("#status").textContent.includes("Real Prism")', 'audio-only replacement')
  assert.equal(await evaluate('document.querySelector("#title").value'), 'Keep My Project Name')
  await evaluate('document.querySelector("[data-id=observatory-song-name]").click()')
  assert.equal(await evaluate('document.querySelector("#text-content").value'), 'SONG B FINAL')
  fs.writeFileSync(path.join(dir, 'gate-summary.json'), JSON.stringify({ templateId, copyId, outputHash,
    songAPreviewHash: digest('song-A-preview.png'), songBPreviewHash: digest('song-B-preview.png'),
    templateLayers: storedTemplate.layout.layers.length, preset: preferences.exportPreset }, null, 2))
  console.log(JSON.stringify({ event: 'phase5-gate', status: 'PASS', dir }))
  app.quit()
}
