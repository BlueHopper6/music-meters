const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const { app } = require('electron')
const delay = ms => new Promise(resolve => setTimeout(resolve, ms))

module.exports = async function mediaQualitySmoke(win) {
  const dir = process.env.MUSICMETERS_MEDIA_SMOKE_DIR
  const evaluate = source => win.webContents.executeJavaScript(source)
  async function wait(source, label) {
    console.log(JSON.stringify({ event: 'media-smoke-wait', label }))
    const deadline = Date.now() + 120000
    while (Date.now() < deadline) { if (await evaluate(source)) return; await delay(100) }
    fs.writeFileSync(path.join(dir, 'failure.png'), (await win.capturePage()).toPNG())
    const state = await evaluate(`(async () => { const audio = document.getElementById('playback-audio'); return { status: document.getElementById('status').textContent, playback: document.getElementById('playback-status').textContent, time: audio.currentTime, paused: audio.paused, frame: document.getElementById('stage').dataset.previewFrame, mixer:(await window.desktop.initial()).project.mixer, undoDisabled:document.getElementById('undo-project').disabled }; })()`)
    throw new Error(`${label}: ${JSON.stringify(state)}`)
  }
  const click = id => evaluate(`document.getElementById(${JSON.stringify(id)}).click()`)
  async function change(id, value) {
    await evaluate(`(() => { const input = document.getElementById(${JSON.stringify(id)}); input.value = ${JSON.stringify(String(value))}; if (input.id === 'time-slider') input.dispatchEvent(new Event('input', { bubbles: true })); input.dispatchEvent(new Event('change', { bubbles: true })); })()`)
    await delay(200)
  }
  await wait('document.getElementById("status").textContent.includes("Real Prism")', 'initial still')
  win.showInactive(); win.setSize(1000, 700)
  await evaluate(`(() => { const create=document.createElement.bind(document); window.mediaTestVideos=[]; document.createElement=function(tag,options){const element=create(tag,options);if(tag==='video')window.mediaTestVideos.push(element);return element;}; })()`)
  await click('import-video')
  await wait('document.getElementById("video-name").textContent.includes("clip") && document.getElementById("cancel-media").hidden && document.getElementById("status").textContent.includes("Real Prism")', 'video import and first frame')
  await change('layer-w', 640); await change('layer-h', 360)
  await change('background-type', 'gradient')
  assert.equal(await evaluate('document.querySelector("#audio-mode option[value=pcm]") === null'), true)
  await evaluate(`(() => { const slider = document.getElementById('mix-audio-volume-slider'); slider.value = '25'; slider.dispatchEvent(new Event('input', {bubbles:true})); })()`)
  assert.equal(await evaluate('document.getElementById("mix-audio-volume").value'), '25')
  assert.equal(await evaluate('window.desktop.initial().then(x => x.project.mixer?.audioVolume ?? 1)'), 1, 'dragging must not prepare a new soundtrack for every pixel')
  await evaluate('document.getElementById("mix-audio-volume-slider").dispatchEvent(new Event("change", {bubbles:true}))')
  await wait('window.desktop.initial().then(x => x.project.mixer?.audioVolume === 0.25)', 'volume slider release')
  await change('mix-audio-volume', 50)
  assert.equal(await evaluate('document.getElementById("mix-audio-volume-slider").value'), '50')
  await change('mix-audio-volume', 25)
  await change('mix-audio-volume', '')
  assert.equal(await evaluate('document.getElementById("mix-audio-volume").value'), '25', 'empty precise input restores its value instead of muting')
  await change('mix-master-volume', 80)
  await change('meter-source', 'audio')
  const routed = await evaluate('window.desktop.initial().then(x => x.project)')
  assert.equal(routed.mixer.meterSource, 'audio'); assert.equal(routed.mixer.audioVolume, 0.25); assert.equal(routed.mixer.masterVolume, 0.8)
  await assert.rejects(() => evaluate(`window.desktop.mediaInfo(${JSON.stringify({ ...routed, layers: routed.layers.map(layer => layer.type === 'video' ? { ...layer, videoPath: path.join(dir, 'unpicked.mp4') } : layer) })})`), /picker/)
  await assert.rejects(() => evaluate(`window.desktop.chooseExportDestination(${JSON.stringify(routed)}, 'copy')`), /unchanged soundtrack/)
  await assert.rejects(() => evaluate(`window.desktop.chooseExportDestination(${JSON.stringify(routed)}, 'pcm')`), /Unsupported audio export option/)
  await click('playback-play')
  await wait('document.getElementById("playback-audio").currentTime > 0.3', 'mixed audio playback')
  await click('playback-play')
  await change('time-slider', 30)
  await wait('document.getElementById("stage").dataset.previewFrame === "30"', 'seek video and meters')
  win.webContents.sendInputEvent({type:'keyDown',keyCode:'F',modifiers:['control']}); win.webContents.sendInputEvent({type:'keyUp',keyCode:'F',modifiers:['control']})
  await wait('document.body.classList.contains("stage-fullscreen") && !document.getElementById("fullscreen-transport").hidden', 'full screen controls')
  assert.equal(await evaluate('document.getElementById("fullscreen-seek-host").contains(document.getElementById("time-slider"))'), true)
  await change('time-slider', 15)
  await wait('document.getElementById("stage").dataset.previewFrame === "15" && document.getElementById("fullscreen-time").textContent.startsWith("00:00.500")', 'full screen seek')
  assert.ok(await evaluate('Math.abs(window.mediaTestVideos.at(-1).currentTime - 0.5) < 0.034'), 'picture seeks to the same timeline time')
  await click('fullscreen-play')
  await wait('document.getElementById("playback-audio").currentTime > 0.65 && !document.getElementById("playback-audio").paused', 'full screen play')
  await wait('Math.abs(window.mediaTestVideos.at(-1).currentTime-document.getElementById("playback-audio").currentTime) < 0.12', 'picture/audio clocks stay synchronized')
  await click('fullscreen-play')
  await wait('document.getElementById("playback-audio").paused && document.getElementById("fullscreen-play").getAttribute("aria-pressed") === "false"', 'full screen pause')
  assert.ok(await evaluate('window.mediaTestVideos.at(-1).paused && Math.abs(window.mediaTestVideos.at(-1).currentTime-document.getElementById("playback-audio").currentTime) < 0.12'))
  await click('fullscreen-muted')
  assert.equal(await evaluate('document.getElementById("playback-audio").muted'), true)
  await click('fullscreen-muted')
  await delay(200)
  const seekBounds = await evaluate(`(() => { const r=document.getElementById('time-slider').getBoundingClientRect();return {left:r.left,right:r.right,top:r.top,bottom:r.bottom,width:innerWidth,height:innerHeight}; })()`)
  assert.ok(seekBounds.left >= 0 && seekBounds.right <= seekBounds.width && seekBounds.top >= 0 && seekBounds.bottom <= seekBounds.height, JSON.stringify(seekBounds))
  fs.writeFileSync(path.join(dir, 'fullscreen-seek.png'), (await win.capturePage()).toPNG())
  win.webContents.sendInputEvent({type:'keyDown',keyCode:'Escape'}); win.webContents.sendInputEvent({type:'keyUp',keyCode:'Escape'})
  await wait('!document.body.classList.contains("stage-fullscreen") && document.querySelector(".timeline").contains(document.getElementById("time-slider"))', 'Escape restores timeline')
  assert.equal(await evaluate('document.querySelectorAll("#time-slider").length'), 1)
  await click('refresh-still')
  await wait('document.getElementById("status").textContent.includes("Real Prism")', 'full-history still')
  win.showInactive(); win.setSize(1000, 700); await delay(250)
  fs.writeFileSync(path.join(dir, 'editor-1000x700.png'), (await win.capturePage()).toPNG())
  await evaluate('document.getElementById("audio-mixer").scrollIntoView({block:"start"})')
  await delay(150)
  fs.writeFileSync(path.join(dir, 'volume-sliders.png'), (await win.capturePage()).toPNG())
  const sliderBounds = await evaluate(`(() => { const r=document.getElementById('mix-audio-volume-slider').getBoundingClientRect(); const n=document.getElementById('mix-audio-volume').getBoundingClientRect();const p=document.querySelector('.properties-panel').getBoundingClientRect();return {slider:r.width,number:n.width,left:r.left,right:n.right,pLeft:p.left,pRight:p.right}; })()`)
  assert.ok(sliderBounds.slider > 60 && sliderBounds.number >= 40 && sliderBounds.left >= sliderBounds.pLeft && sliderBounds.right <= sliderBounds.pRight, JSON.stringify(sliderBounds))
  await evaluate('document.getElementById("template-name").value = ""; document.getElementById("save-template").click()')
  await wait('!document.getElementById("save-template-modal").hidden', 'themed template dialog')
  assert.equal(await evaluate('document.activeElement.id'), 'template-name')
  const fieldStyle = await evaluate(`(() => { const s=getComputedStyle(document.getElementById('template-name')); return {height:s.height,background:s.backgroundColor,padding:s.paddingLeft,shadow:s.boxShadow}; })()`)
  assert.equal(fieldStyle.shadow, 'none'); assert.equal(fieldStyle.height, '38px'); assert.equal(fieldStyle.background, 'rgb(12, 12, 15)'); assert.equal(fieldStyle.padding, '11px')
  await delay(150); fs.writeFileSync(path.join(dir, 'save-template.png'), (await win.capturePage()).toPNG())
  await evaluate(`(() => {const input=document.getElementById('template-name');input.value='Controls test';input.dispatchEvent(new KeyboardEvent('keydown',{key:'Enter',bubbles:true}));})()`)
  await wait('document.getElementById("save-template-modal").hidden && document.getElementById("status").textContent.includes("Saved layout template:")', 'template Enter saves')
  const bounds = await evaluate(`(() => { const r = document.getElementById('import-video').getBoundingClientRect(); const p = document.querySelector('.center-panel').getBoundingClientRect(); return {left:r.left,right:r.right,pLeft:p.left,pRight:p.right}; })()`)
  assert.ok(bounds.left >= bounds.pLeft && bounds.right <= bounds.pRight, JSON.stringify(bounds))
  process.env.PHASE2_TEST_PROJECT_PATH = path.join(dir, 'project', 'project.json')
  await click('save-project')
  await wait(`window.desktop.initial().then(x => x.projectPath === ${JSON.stringify(process.env.PHASE2_TEST_PROJECT_PATH)})`, 'save')
  const stored = JSON.parse(fs.readFileSync(process.env.PHASE2_TEST_PROJECT_PATH, 'utf8'))
  assert.ok(stored.layers.find(layer => layer.type === 'video').videoRelativePath)
  assert.equal(stored.layers.find(layer => layer.type === 'video').videoPath, undefined)
  fs.writeFileSync(path.join(dir, 'project-snapshot.json'), JSON.stringify(await evaluate('window.desktop.initial().then(x => x.project)'), null, 2))
  await change('mix-audio-volume', 50)
  await click('undo-project')
  await wait('window.desktop.initial().then(x => x.project.mixer.audioVolume === 0.25 && !document.getElementById("editor-screen").inert)', 'undo mixer')
  await click('redo-project')
  await wait('window.desktop.initial().then(x => x.project.mixer.audioVolume === 0.5 && !document.getElementById("editor-screen").inert)', 'redo mixer')
  await click('undo-project')
  await wait('window.desktop.initial().then(x => x.project.mixer.audioVolume === 0.25 && !document.getElementById("editor-screen").inert)', 'restore mix')
  await change('mix-master-volume', 90)
  // Automated runs bypass native close guards to ensure teardown. Exercise the
  // production close-request event here without closing the test window.
  const closeWindow = win.close.bind(win)
  win.close = () => win.webContents.send('app-close-requested')
  win.webContents.sendInputEvent({type:'keyDown',keyCode:'Q',modifiers:['control']}); win.webContents.sendInputEvent({type:'keyUp',keyCode:'Q',modifiers:['control']})
  await wait('!document.getElementById("unsaved-changes-modal").hidden', 'Ctrl+Q preserves unsaved changes guard')
  await click('unsaved-changes-cancel')
  win.close = closeWindow
  await change('mix-master-volume', 80)
  await change('export-preset', '720p')
  for (const mode of ['master', 'flac', 'aac']) {
    const extension = mode === 'aac' ? 'mp4' : 'mkv'
    const output = path.join(dir, `export-${mode}.${extension}`)
    process.env.PHASE2_TEST_OUTPUT_PATH = output
    await change('audio-mode', mode)
    await click('open-export')
    await wait('!document.getElementById("export-modal").hidden', `${mode} dialog`)
    if (mode === 'flac') { await delay(200); fs.writeFileSync(path.join(dir, 'export-dialog.png'), (await win.capturePage()).toPNG()) }
    await click('render-mp4')
    await wait(`document.getElementById('status').textContent.includes(${JSON.stringify(output)}) && document.getElementById('status').textContent.includes('ready:')`, `${mode} export`)
    assert.ok(fs.existsSync(output))
  }
  // Reopen the saved file through the same IPC used by the UI.
  const reopened = await evaluate('window.desktop.openProject()')
  assert.equal(reopened.project.layers.find(layer => layer.type === 'video').videoPath, process.env.MUSICMETERS_TEST_VIDEO)
  await click('new-project')
  await wait('window.desktop.initial().then(x => !x.project.audioPath && !x.project.layers.length)', 'new blank project')
  await click('import-video')
  await wait('document.getElementById("cancel-media").hidden && document.getElementById("status").textContent.includes("Real Prism") && window.desktop.initial().then(x => x.metadata && !x.project.audioPath)', 'video-only import')
  process.env.PHASE2_TEST_OUTPUT_PATH = path.join(dir, 'video-only.mkv')
  await change('audio-mode', 'flac'); await click('open-export'); await click('render-mp4')
  await wait('document.getElementById("status").textContent.includes("video-only.mkv") && document.getElementById("status").textContent.includes("ready:")', 'video-only export')
  process.env.MUSICMETERS_TEST_VIDEO = path.join(dir, 'silent.mp4')
  await click('import-video')
  await wait('document.getElementById("cancel-media").hidden && document.getElementById("video-name").textContent.includes("silent") && document.getElementById("status").textContent.includes("Real Prism")', 'silent video import')
  await change('canvas-orientation', 'portrait')
  await change('export-preset', '2160p')
  process.env.PHASE2_TEST_OUTPUT_PATH = path.join(dir, 'silent-4k-portrait.mkv')
  fs.writeFileSync(path.join(dir, 'silent-project.json'), JSON.stringify(await evaluate('window.desktop.initial()'), null, 2))
  await click('open-export'); await click('render-mp4')
  await wait('document.getElementById("status").textContent.includes("silent-4k-portrait.mkv") && document.getElementById("status").textContent.includes("ready:")', 'silent 4K portrait export')
  process.env.MUSICMETERS_TEST_STILL_OUTPUT=path.join(dir,'video-still.png')
  await click('open-export');await click('export-still')
  await wait('document.getElementById("status").textContent.startsWith("PNG ready:")','video-backed PNG')
  const png=fs.readFileSync(path.join(dir,'video-still.png'))
  assert.deepEqual([png.readUInt32BE(16),png.readUInt32BE(20)],[2160,3840])
  console.log(JSON.stringify({ event: 'media-quality-pass', bounds, seekBounds, sliderBounds, fieldStyle, exports: 5, metadata: reopened.metadata }))
  app.quit()
}
