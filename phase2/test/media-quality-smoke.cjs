const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const { app } = require('electron')
const delay = ms => new Promise(resolve => setTimeout(resolve, ms))

module.exports = async function mediaQualitySmoke(win) {
  const dir = process.env.MUSICMETERS_MEDIA_SMOKE_DIR
  const evaluate = source => win.webContents.executeJavaScript(source)
  async function wait(source, label) {
    console.log(JSON.stringify({ event: 'media-smoke-wait', label }))
    const deadline = Date.now() + 120000
    while (Date.now() < deadline) { if (await evaluate(source)) return; await delay(100) }
    fs.writeFileSync(path.join(dir, 'failure.png'), (await win.capturePage()).toPNG())
    const state = await evaluate(`(async () => { const audio = document.getElementById('playback-audio'); return { status: document.getElementById('status').textContent, playback: document.getElementById('playback-status').textContent, time: audio.currentTime, paused: audio.paused, frame: document.getElementById('stage').dataset.previewFrame, mixer:(await window.desktop.initial()).project.mixer, undoDisabled:document.getElementById('undo-project').disabled }; })()`)
    throw new Error(`${label}: ${JSON.stringify(state)}`)
  }
  const click = id => evaluate(`document.getElementById(${JSON.stringify(id)}).click()`)
  async function change(id, value) {
    await evaluate(`(() => { const input = document.getElementById(${JSON.stringify(id)}); input.value = ${JSON.stringify(String(value))}; if (input.id === 'time-slider') input.dispatchEvent(new Event('input', { bubbles: true })); input.dispatchEvent(new Event('change', { bubbles: true })); })()`)
    await delay(200)
  }
  await wait('document.getElementById("status").textContent.includes("Real Prism")', 'initial still')
  await click('import-video')
  await wait('document.getElementById("video-name").textContent.includes("clip") && document.getElementById("cancel-media").hidden && document.getElementById("status").textContent.includes("Real Prism")', 'video import and first frame')
  await change('layer-w', 640); await change('layer-h', 360)
  await change('background-type', 'gradient')
  await change('mix-audio-volume', 25)
  await change('mix-master-volume', 80)
  await change('meter-source', 'audio')
  const routed = await evaluate('window.desktop.initial().then(x => x.project)')
  assert.equal(routed.mixer.meterSource, 'audio'); assert.equal(routed.mixer.audioVolume, 0.25); assert.equal(routed.mixer.masterVolume, 0.8)
  await assert.rejects(() => evaluate(`window.desktop.mediaInfo(${JSON.stringify({ ...routed, layers: routed.layers.map(layer => layer.type === 'video' ? { ...layer, videoPath: path.join(dir, 'unpicked.mp4') } : layer) })})`), /picker/)
  await assert.rejects(() => evaluate(`window.desktop.chooseExportDestination(${JSON.stringify(routed)}, 'copy')`), /unchanged soundtrack/)
  await click('playback-play')
  await wait('document.getElementById("playback-audio").currentTime > 0.3', 'mixed audio playback')
  await click('playback-play')
  await change('time-slider', 30)
  await wait('document.getElementById("stage").dataset.previewFrame === "30"', 'seek video and meters')
  await click('refresh-still')
  await wait('document.getElementById("status").textContent.includes("Real Prism")', 'full-history still')
  win.showInactive(); win.setSize(1000, 700); await delay(250)
  fs.writeFileSync(path.join(dir, 'editor-1000x700.png'), (await win.capturePage()).toPNG())
  const bounds = await evaluate(`(() => { const r = document.getElementById('import-video').getBoundingClientRect(); const p = document.querySelector('.center-panel').getBoundingClientRect(); return {left:r.left,right:r.right,pLeft:p.left,pRight:p.right}; })()`)
  assert.ok(bounds.left >= bounds.pLeft && bounds.right <= bounds.pRight, JSON.stringify(bounds))
  process.env.PHASE2_TEST_PROJECT_PATH = path.join(dir, 'project', 'project.json')
  await click('save-project')
  await wait(`window.desktop.initial().then(x => x.projectPath === ${JSON.stringify(process.env.PHASE2_TEST_PROJECT_PATH)})`, 'save')
  const stored = JSON.parse(fs.readFileSync(process.env.PHASE2_TEST_PROJECT_PATH, 'utf8'))
  assert.ok(stored.layers.find(layer => layer.type === 'video').videoRelativePath)
  assert.equal(stored.layers.find(layer => layer.type === 'video').videoPath, undefined)
  fs.writeFileSync(path.join(dir, 'project-snapshot.json'), JSON.stringify(await evaluate('window.desktop.initial().then(x => x.project)'), null, 2))
  await change('mix-audio-volume', 50)
  await click('undo-project')
  await wait('window.desktop.initial().then(x => x.project.mixer.audioVolume === 0.25 && !document.getElementById("editor-screen").inert)', 'undo mixer')
  await click('redo-project')
  await wait('window.desktop.initial().then(x => x.project.mixer.audioVolume === 0.5 && !document.getElementById("editor-screen").inert)', 'redo mixer')
  await click('undo-project')
  await wait('window.desktop.initial().then(x => x.project.mixer.audioVolume === 0.25 && !document.getElementById("editor-screen").inert)', 'restore mix')
  await change('export-preset', '720p')
  for (const mode of ['master', 'flac', 'pcm', 'aac']) {
    const extension = mode === 'aac' ? 'mp4' : mode === 'pcm' ? 'mov' : 'mkv'
    const output = path.join(dir, `export-${mode}.${extension}`)
    process.env.PHASE2_TEST_OUTPUT_PATH = output
    await change('audio-mode', mode)
    await click('open-export')
    await wait('!document.getElementById("export-modal").hidden', `${mode} dialog`)
    if (mode === 'pcm') { await delay(200); fs.writeFileSync(path.join(dir, 'export-dialog.png'), (await win.capturePage()).toPNG()) }
    await click('render-mp4')
    await wait(`document.getElementById('status').textContent.includes(${JSON.stringify(output)}) && document.getElementById('status').textContent.includes('ready:')`, `${mode} export`)
    assert.ok(fs.existsSync(output))
  }
  // Reopen the saved file through the same IPC used by the UI.
  const reopened = await evaluate('window.desktop.openProject()')
  assert.equal(reopened.project.layers.find(layer => layer.type === 'video').videoPath, process.env.MUSICMETERS_TEST_VIDEO)
  await click('new-project')
  await wait('window.desktop.initial().then(x => !x.project.audioPath && !x.project.layers.length)', 'new blank project')
  await click('import-video')
  await wait('document.getElementById("cancel-media").hidden && document.getElementById("status").textContent.includes("Real Prism") && window.desktop.initial().then(x => x.metadata && !x.project.audioPath)', 'video-only import')
  process.env.PHASE2_TEST_OUTPUT_PATH = path.join(dir, 'video-only.mov')
  await change('audio-mode', 'pcm'); await click('open-export'); await click('render-mp4')
  await wait('document.getElementById("status").textContent.includes("video-only.mov") && document.getElementById("status").textContent.includes("ready:")', 'video-only export')
  process.env.MUSICMETERS_TEST_VIDEO = path.join(dir, 'silent.mp4')
  await click('import-video')
  await wait('document.getElementById("cancel-media").hidden && document.getElementById("video-name").textContent.includes("silent") && document.getElementById("status").textContent.includes("Real Prism")', 'silent video import')
  await change('canvas-orientation', 'portrait')
  await change('export-preset', '2160p')
  process.env.PHASE2_TEST_OUTPUT_PATH = path.join(dir, 'silent-4k-portrait.mov')
  await click('open-export'); await click('render-mp4')
  await wait('document.getElementById("status").textContent.includes("silent-4k-portrait.mov") && document.getElementById("status").textContent.includes("ready:")', 'silent 4K portrait export')
  console.log(JSON.stringify({ event: 'media-quality-pass', bounds, exports: 6, metadata: reopened.metadata }))
  app.quit()
}
