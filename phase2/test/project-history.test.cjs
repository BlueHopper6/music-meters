const { test } = require('node:test')
const assert = require('node:assert/strict')
const { ProjectHistory } = require('../project-history.cjs')
const { compositionProject } = require('../project.cjs')

test('undo/redo restores independent copies of real project edits', () => {
  const history = new ProjectHistory()
  const project = compositionProject()
  history.reset(project)
  const original = structuredClone(project)
  project.layers[0].x += 1
  history.record(project)
  assert.deepEqual(history.move(-1), original)
  const restored = history.peek(1)
  restored.layers[0].x = 900
  assert.equal(history.move(1).layers[0].x, project.layers[0].x)
  assert.equal(history.canRedo, false)
})

test('typing and drag groups are single edits with explicit boundaries', () => {
  const history = new ProjectHistory()
  const project = compositionProject()
  history.reset(project)
  for (const title of ['H', 'He', 'Hello']) history.record({ ...project, title }, 'title')
  assert.equal(history.move(-1).title, project.title)
  assert.equal(history.move(1).title, 'Hello')
  history.endGroup()
  history.record({ ...project, title: 'Hello again' }, 'title')
  assert.equal(history.move(-1).title, 'Hello')
})

test('edit history never captures seek positions or clears redo for seeking', () => {
  const history = new ProjectHistory()
  const project = compositionProject()
  history.reset(project)
  history.record({ ...project, previewFrame: 90 })
  assert.equal(history.canUndo, false)
  history.record({ ...project, title: 'Edit', previewFrame: 90 })
  assert.equal(history.move(-1).previewFrame, 0)
  history.record({ ...project, previewFrame: 120 })
  assert.equal(history.canRedo, true)
  assert.equal(history.move(1).title, 'Edit')
  assert.equal(history.peek(-1).previewFrame, 0)
  history.replaceCurrent({ ...project, title: 'Edit', previewFrame: 150 })
  assert.equal(history.move(-1).previewFrame, 0)
  assert.equal(history.move(1).previewFrame, 0)
})

test('new edits discard redo; save replaces current paths without creating an edit', () => {
  const history = new ProjectHistory()
  const project = compositionProject()
  history.reset(project)
  history.record({ ...project, title: 'A' })
  history.replaceCurrent({ ...project, title: 'A', audioPath: 'saved.wav' })
  assert.equal(history.move(-1).title, project.title)
  assert.equal(history.move(1).audioPath, 'saved.wav')
  history.move(-1)
  history.record({ ...project, title: 'B' })
  assert.equal(history.canRedo, false)
})

test('history is bounded and reset cannot cross project sessions', () => {
  const history = new ProjectHistory(2)
  const project = compositionProject()
  history.reset(project)
  for (const title of ['A', 'B', 'C']) history.record({ ...project, title })
  assert.equal(history.move(-1).title, 'B')
  assert.equal(history.move(-1).title, 'A')
  assert.equal(history.move(-1), null)
  history.reset({ ...project, title: 'New project' })
  assert.equal(history.canUndo, false)
  assert.equal(history.canRedo, false)
  assert.throws(() => history.peek(0), /direction/)
  assert.throws(() => new ProjectHistory(0), /limit/)
})
